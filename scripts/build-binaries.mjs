#!/usr/bin/env node
// Builds single-file emberdeck binaries with the dashboard embedded.
//
//   node scripts/build-binaries.mjs                       # all targets
//   node scripts/build-binaries.mjs --targets linux-x64   # selected targets
//   node scripts/build-binaries.mjs --dashboard-dir path  # custom dashboard build
//
// Requires: bun, a built core (`pnpm build`) and a built dashboard.
// Output: dist-bin/emberdeck-v<version>-<target>.tar.gz plus checksums.txt

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ALL_TARGETS = ["darwin-arm64", "darwin-x64", "linux-x64", "linux-arm64"];

const { values } = parseArgs({
  options: {
    targets: { type: "string" },
    "dashboard-dir": { type: "string" },
    out: { type: "string", default: join(ROOT, "dist-bin") },
  },
});

const targets = values.targets ? values.targets.split(",").map((t) => t.trim()) : ALL_TARGETS;
for (const t of targets) {
  if (!ALL_TARGETS.includes(t)) throw new Error(`Unknown target "${t}". Known: ${ALL_TARGETS.join(", ")}`);
}

const version = JSON.parse(readFileSync(join(ROOT, "packages/cli/package.json"), "utf8")).version;
const dashboardDir = values["dashboard-dir"] ?? join(ROOT, "packages/dashboard/dist");
if (!existsSync(join(dashboardDir, "index.html"))) {
  throw new Error(`No dashboard build at ${dashboardDir}. Run \`pnpm build\` first.`);
}
if (!existsSync(join(ROOT, "packages/core/dist/index.js"))) {
  throw new Error("Core is not built. Run `pnpm build` first.");
}

// 1. Embed the dashboard as base64 strings.
const files = {};
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files[relative(dashboardDir, full).split("\\").join("/")] = readFileSync(full).toString("base64");
  }
};
walk(dashboardDir);
const genPath = join(ROOT, "packages/cli/standalone/embedded-dashboard.gen.ts");
writeFileSync(
  genPath,
  `// Generated by scripts/build-binaries.mjs — do not edit.\nexport const files: Record<string, string> = ${JSON.stringify(files)};\n`,
);
const embeddedKb = Math.round(Object.values(files).reduce((n, b) => n + b.length, 0) / 1024);
console.log(`Embedded ${Object.keys(files).length} dashboard files (${embeddedKb} KB base64)`);

// 2. Compile one binary per target and package it.
rmSync(values.out, { recursive: true, force: true });
mkdirSync(values.out, { recursive: true });
const checksums = [];

for (const target of targets) {
  const name = `emberdeck-v${version}-${target}`;
  const stageDir = join(values.out, name);
  mkdirSync(stageDir, { recursive: true });
  console.log(`Compiling ${target}…`);
  execFileSync(
    "bun",
    [
      "build",
      "--compile",
      "--minify",
      "--sourcemap",
      `--target=bun-${target}`,
      join(ROOT, "packages/cli/standalone/entry.ts"),
      "--outfile",
      join(stageDir, "emberdeck"),
    ],
    { stdio: "inherit", cwd: ROOT },
  );
  if (target.startsWith("darwin")) {
    if (process.platform === "darwin") {
      // Apple Silicon refuses to run unsigned binaries; an ad-hoc signature is enough.
      execFileSync("codesign", ["--force", "--sign", "-", join(stageDir, "emberdeck")], { stdio: "inherit" });
    } else {
      console.warn("  ! macOS binary built on non-macOS host: not codesigned. Build releases on macOS.");
    }
  }
  cpSync(join(ROOT, "LICENSE"), join(stageDir, "LICENSE"));
  cpSync(join(ROOT, "README.md"), join(stageDir, "README.md"));

  const archive = `${name}.tar.gz`;
  execFileSync("tar", ["-czf", archive, "-C", stageDir, "emberdeck", "LICENSE", "README.md"], { cwd: values.out });
  rmSync(stageDir, { recursive: true, force: true });
  const sha = createHash("sha256").update(readFileSync(join(values.out, archive))).digest("hex");
  checksums.push(`${sha}  ${archive}`);
  console.log(`  → ${archive} (${sha.slice(0, 12)}…)`);
}

writeFileSync(join(values.out, "checksums.txt"), `${checksums.join("\n")}\n`);
console.log(`Done: ${values.out}`);
